// Vite plugins of the phone web app (npm run build:web). The desktop build
// does not use any of them.

import { readFileSync } from 'fs';
import { createHash } from 'crypto';
import { createRequire } from 'module';
import { fileURLToPath, URL } from 'url';

const require = createRequire(import.meta.url);

// The pure sync rules live in gdrive-utils.cjs, which Electron's main process
// requires. The web app imports the very same file as an ES module through
// 'virtual:gdrive-utils', so both apps always follow identical rules.
const SHARED = {
  'virtual:gdrive-utils': fileURLToPath(new URL('../gdrive-utils.cjs', import.meta.url))
};

// CommonJS source -> ES module with the same named exports.
export function cjsToEsm(code, names) {
  return [
    'const __cjs = { exports: {} };',
    '(function (module, exports) {',
    code,
    '})(__cjs, __cjs.exports);',
    ...names.map(name => `export const ${name} = __cjs.exports.${name};`),
    'export default __cjs.exports;'
  ].join('\n');
}

export function sharedCjs() {
  return {
    name: 'we-shared-cjs',
    resolveId(id) {
      return SHARED[id] ? '\0' + id : null;
    },
    load(id) {
      const file = SHARED[id.replace(/^\0/, '')];
      if (!id.startsWith('\0') || !file) return null;
      this.addWatchFile(file);
      delete require.cache[file];
      return cjsToEsm(readFileSync(file, 'utf8'), Object.keys(require(file)));
    }
  };
}

// The web app has its own page, web.html, so the desktop index.html stays as
// it is. On the published site it must answer at /app/, so it is written out
// as index.html, and the dev server serves it at the base address too.
export function webEntryAsIndex(base) {
  return {
    name: 'we-web-entry-as-index',
    enforce: 'post',
    configureServer(server) {
      server.middlewares.use((req, _res, next) => {
        const path = (req.url || '').split(/[?#]/)[0];
        if (path === base || path === base + 'index.html') req.url = base + 'web.html' + (req.url || '').slice(path.length);
        next();
      });
    },
    generateBundle(_options, bundle) {
      const page = bundle['web.html'];
      if (!page) return;
      delete bundle['web.html'];
      this.emitFile({ type: 'asset', fileName: 'index.html', source: page.source });
    }
  };
}

// Files that come from public-web/ as they are and the app needs offline.
const PUBLIC_FILES = ['manifest.webmanifest', 'favicon.png', 'apple-touch-icon-v4.png', 'icon-192-v4.png', 'icon-512-v4.png'];

// tag: a hash of what the build ships, so a new icon or manifest reaches
// installed apps even when the version number stays the same.
export function serviceWorkerSource(version, files, tag = '') {
  return `// Generated by the build: WE Time Tracker ${version}
const CACHE = 'we-time-tracker-${version}${tag ? '-' + tag : ''}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('we-time-tracker-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Requests to Google go to the network untouched. The page itself comes from
// the network first (it names the current files) and from the cache offline;
// everything else from the cache first.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request)
      .then(response => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then(cache => cache.put('./', copy));
        }
        return response;
      })
      .catch(() => caches.match('./')));
    return;
  }
  event.respondWith(caches.match(request).then(hit => hit || fetch(request).then(response => {
    if (response.ok) {
      const copy = response.clone();
      caches.open(CACHE).then(cache => cache.put(request, copy));
    }
    return response;
  })));
});
`;
}

export function serviceWorker(version) {
  return {
    name: 'we-web-service-worker',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      // Fonts come in many alphabets; the browser loads only the ones the
      // page needs, and the worker keeps them as they are first used.
      const built = Object.keys(bundle).filter(name => !name.endsWith('.map') && !/\.html$/.test(name) && !/\.woff2?$/.test(name));
      const files = ['./', ...built.map(name => './' + name), ...PUBLIC_FILES.map(name => './' + name)];
      // Built names carry content hashes; public files are hashed here.
      const hash = createHash('sha256').update(built.sort().join('\n'));
      PUBLIC_FILES.forEach(name => hash.update(readFileSync(fileURLToPath(new URL('../public-web/' + name, import.meta.url)))));
      const tag = hash.digest('hex').slice(0, 10);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorkerSource(version, files, tag) });
    }
  };
}
